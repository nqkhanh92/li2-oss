-- 1b.2: the rolling summary is per-SESSION (§16), not per (org,user). Add session_id
-- and re-scope the unique index. Existing rows: none in prod (memory unpopulated until now).
ALTER TABLE agent.agent_memory
  ADD COLUMN session_id uuid REFERENCES agent.agent_sessions(id) ON DELETE CASCADE;

DROP INDEX IF EXISTS agent.uq_agent_memory_scope;               -- was (org_id,user_id,tier)

-- Two PARTIAL unique indexes, split on whether the row is session-scoped:
--   * session tiers (summary) key on (session_id, tier) — one summary per session.
--   * future per-user tiers (preferences/facts/…, session_id IS NULL) key on
--     (org_id, user_id, tier) — one per user, as the P0 index did.
-- A single (session_id, tier) unique index would NOT guard the per-user rows, because
-- NULLs are distinct in a Postgres unique index: every session_id-NULL row would be
-- considered unique and the per-user "one row per (org,user,tier)" rule would silently
-- vanish. Partial indexes keep each scope's rule enforced independently.
CREATE UNIQUE INDEX uq_agent_memory_session_tier
  ON agent.agent_memory (session_id, tier)
  WHERE session_id IS NOT NULL;
CREATE UNIQUE INDEX uq_agent_memory_user_tier
  ON agent.agent_memory (org_id, user_id, tier)
  WHERE session_id IS NULL;

-- 1b.2: compaction cuts the history on a whole user->assistant turn boundary, and the
-- summary watermark must point at ONE unambiguous "last aged-out row". `created_at` is
-- unsafe for BOTH: end_turn writes a turn's user + assistant rows in a SINGLE transaction,
-- so both carry the same now() (transaction timestamp). ORDER BY created_at is then a tie
-- with UNDEFINED row order — a pair can come back [assistant, user] and the boundary cut
-- splits it, orphaning an answer from its question. Add a monotonic per-row sequence and
-- key ordering + the watermark on it instead. nextval() is assigned in statement-execution
-- order, so within any one pair the user row always gets a smaller `seq` than its assistant
-- row — the intra-pair order is guaranteed regardless of tied timestamps or concurrent
-- writers. (Existing rows: none in prod; the identity backfill runs in physical/insertion
-- order, which for any already-written pair is user-then-assistant anyway.)
ALTER TABLE agent.agent_messages
  ADD COLUMN seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX idx_agent_messages_session_seq
  ON agent.agent_messages (session_id, seq);
